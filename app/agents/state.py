from typing import TypedDict, List, Optional, Annotated
import operator

class CandidateState(TypedDict):
    """
    The shared memory graph state passed between all AI Agents in LangGraph.
    Each node reads from this state and returns only the keys it wants to update.
    """
    # 1. Input & Identity Data
    candidate_id: str
    anonymized_id: str          # Generated by Parser Agent after PII masking
    full_name: str              # Stored securely, hidden from Screening/Assessment agents
    email: str
    job_id: str
    job_description: str
    raw_resume_text: str

    # 2. Parser & Anonymizer Agent Outputs
    scrubbed_resume_text: str   # Resume with Name, Phone, Email stripped out
    extracted_skills: List[str]
    years_of_experience: float

    # 3. Screener Agent (RAG/Semantic Match) Outputs
    missing_skills: List[str]
    match_score: float          # 0.0 to 100.0
    screening_feedback: str     # Explainable reasoning for the score

    # 4. Dynamic Assessment Agent Outputs
    technical_questions: List[str]
    assessment_score: Optional[float]

    # 5. Coordinator Agent (Calendar & Email) Outputs
    proposed_slots: List[str]   # Fetched free slots from Interviewer's calendar
    confirmed_slot: Optional[str]
    meeting_link: Optional[str]
    email_sent: bool
    latest_email_body: Optional[str]

    # 6. Pipeline Tracking & Explainable AI Audit Trail
    status: str
    # operator.add ensures every agent appends its step to the log instead of overwriting!
    audit_log: Annotated[List[str], operator.add]